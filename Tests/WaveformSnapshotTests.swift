import SwiftUI
import XCTest
@testable import AudioWhisper

/// Baselines for each `WaveformContainer` style and status — the waveform the
/// recorder overlay draws. Kept from the retired legacy snapshot suite because
/// the waveform code still ships.
@MainActor
final class WaveformSnapshotTests: SnapshotTestCase {
    let defaults = AppDefaults.defaults

    override func setUp() async throws {
        try await super.setUp()
        defaults.removeObject(forKey: "waveformStyle")
        defaults.removeObject(forKey: "visualIntensity")
    }

    // MARK: - Waveform Style Snapshots

    func testWaveformContainerClassicSnapshot() {
        defaults.set(WaveformStyle.classic.rawValue, forKey: "waveformStyle")
        defaults.set(VisualIntensity.balanced.rawValue, forKey: "visualIntensity")

        let view = WaveformContainer(
            status: .recording,
            audioLevel: 0.6,
            waveformSamples: [],
            frequencyBands: Array(repeating: 0.5, count: 8),
            onTap: {}
        )
        .frame(width: 280, height: 160)

        assertSnapshot(
            view,
            named: "WaveformContainer-classic-recording",
            size: CGSize(width: 320, height: 200),
            colorScheme: .dark,
            tolerance: 0.05  // animated view — frame content varies per render
        )
    }

    func testWaveformContainerReadySnapshot() {
        defaults.set(WaveformStyle.classic.rawValue, forKey: "waveformStyle")

