import AppKit
import XCTest
@testable import AudioWhisper

/// Runs against a private, uniquely named pasteboard: the user's clipboard is
/// never touched.
@MainActor
final class ClipboardKeeperTests: XCTestCase {
    private var board: NSPasteboard!
    private var keeper: ClipboardKeeper!

    override func setUp() {
        super.setUp()
        board = NSPasteboard(name: NSPasteboard.Name("audiowhisper.tests.\(UUID().uuidString)"))
        keeper = ClipboardKeeper(pasteboard: board)
    }

    override func tearDown() {
        board.releaseGlobally()
        board = nil
        keeper = nil
        super.tearDown()
    }

    func testEveryItemAndRepresentationComesBack() {
        let custom = NSPasteboard.PasteboardType("com.example.rich")
        let first = NSPasteboardItem()
        first.setString("plain", forType: .string)
        first.setData(Data([1, 2, 3]), forType: custom)
        let second = NSPasteboardItem()
        second.setString("https://example.com", forType: .URL)
        board.clearContents()
        board.writeObjects([first, second])

        let saved = keeper.save()
        let loan = UUID()
        keeper.copy("dictated", loan: loan)
        XCTAssertTrue(keeper.restore(saved, loan: loan))

        XCTAssertEqual(board.pasteboardItems?.count, 2)
        XCTAssertEqual(board.pasteboardItems?.first?.string(forType: .string), "plain")
        XCTAssertEqual(board.pasteboardItems?.first?.data(forType: custom), Data([1, 2, 3]))
        XCTAssertEqual(board.pasteboardItems?.last?.string(forType: .URL), "https://example.com")
        XCTAssertNil(board.string(forType: ClipboardKeeper.loanType))
    }

    func testTheTranscriptIsMarkedForClipboardHistoryApps() {
        keeper.copy("dictated", loan: UUID())
        XCTAssertEqual(board.string(forType: .string), "dictated")
        XCTAssertTrue(board.types?.contains(ClipboardKeeper.transientType) == true)
        XCTAssertTrue(board.types?.contains(ClipboardKeeper.autoGeneratedType) == true)
    }

    func testSomethingCopiedMeanwhileIsNeverOverwritten() {
        setText("before")
        let saved = keeper.save()
        let loan = UUID()
        keeper.copy("dictated", loan: loan)
        setText("copied by the user afterwards")

        XCTAssertFalse(keeper.restore(saved, loan: loan))
        XCTAssertEqual(board.string(forType: .string), "copied by the user afterwards")
    }

    func testANewerDictationKeepsTheClipboard() {
        setText("before")
        let saved = keeper.save()
        let older = UUID()
        keeper.copy("first dictation", loan: older)
        keeper.copy("second dictation", loan: UUID())

        XCTAssertFalse(keeper.restore(saved, loan: older))
        XCTAssertEqual(board.string(forType: .string), "second dictation")
    }

    func testAnEmptyClipboardIsEmptyAgainAfterwards() {
        board.clearContents()
        let saved = keeper.save()
        let loan = UUID()
        keeper.copy("dictated", loan: loan)

        XCTAssertTrue(keeper.restore(saved, loan: loan))
        XCTAssertNil(board.string(forType: .string))
        XCTAssertEqual(board.pasteboardItems?.count ?? 0, 0)
    }

    private func setText(_ text: String) {
        board.clearContents()
        board.setString(text, forType: .string)
    }
}
